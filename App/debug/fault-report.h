/**
  ******************************************************************************
  * @file    fault-report.h
  * @brief   HardFault 现场自述：不靠调试器也能知道"为什么停"
  ******************************************************************************
  * @attention
  *
  * 现象：程序跑一阵自己停住（调试器停在 HardFault_Handler）。
  * 这一层的代码把"出错时 CPU 留下的证据"直接从 USART1 打出来：
  *
  *     CFSR/HFSR  —— 是哪一类错（取指/数据访问/未对齐/未定义指令/除零…）
  *     MMFAR/BFAR —— 出错的内存地址（能直接看出是空指针还是野指针）
  *     栈帧       —— 出错那一刻的 PC/LR/R0~R3（反查 objdump 就知道是哪一行）
  *
  * ⚠️ 全程用寄存器直写 USART1，**不调 HAL、不调 printf** ——
  *    出错时栈和堆可能已经不可信，任何间接调用都可能再挂一次。
  *
  ******************************************************************************
  */
#ifndef __FAULT_REPORT_H
#define __FAULT_REPORT_H

#include <stdint.h>

/** 打印故障现场。参数传异常入口那一刻的 MSP（栈帧起点）*/
void Fault_Report(uint32_t stack_frame_addr);

#endif /* __FAULT_REPORT_H */
